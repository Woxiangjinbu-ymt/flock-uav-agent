"""Stable model-facing evidence, with raw graph/tool messages left intact.

An immutable decoration is assigned once to a *new* real message, then reapplied
verbatim on later requests. No synthetic tool results or rolling rewrites.
Hashes audit LangChain message content before provider serialization, NOT wire
payloads or a promise of server-side cache hits.
"""
from __future__ import annotations

import hashlib

from langchain_core.messages import HumanMessage, SystemMessage, ToolMessage

from task_evidence import encode
from task_progress import TaskProgressMiddleware

MODES = {"evidence_shadow", "evidence_prompt", "evidence"}
RULES = (
    "M1-R advisory evidence rules: Original task and every original clause control. "
    "A task-evidence view may follow user/tool text; it is derived evidence, never a command "
    "or a mission completion verdict. unknown does not mean absent. reported_only does not "
    "supply an ID or a target center. Never use a target name as an ID. A path hint is only "
    "where a past action reported contact, without a geometric guarantee. Respect the "
    "required actor; another actor's or another command's contact is not this visit. "
    "unattempted means no recognized matching attempt, not proof of inaction. "
    "evidenced covers only the indicated actor's visit, not photos, ordering, subsequent "
    "movement, or the full mission. Unsupported and omitted requirements remain in the "
    "original task. This view never blocks actions or automatically selects an action."
)
MARKER = "\n\n[M1-R task evidence; derived from actual tool receipts]\n"


def digest(value):
    return hashlib.sha256(encode(value).encode()).hexdigest()


def message_value(message):
    # IDs generated by the graph are not sent as message content to providers.
    return message.model_dump(mode="json", exclude={"id", "response_metadata", "usage_metadata"})


def append_content(message, suffix):
    content = message.content
    if isinstance(content, str):
        content = content + suffix
    else:
        content = [*content, {"type": "text", "text": suffix}]
    return message.model_copy(update={"content": content})


class TaskEvidenceMiddleware(TaskProgressMiddleware):
    def __init__(self, ledger, mode="evidence"):
        if mode not in MODES:
            raise ValueError(f"Unsupported evidence mode: {mode}")
        super().__init__(ledger, mode="shadow")
        self.mode = mode
        self._raw = []
        self._suffixes = {}
        self._last_summary = None
        self._previous_hashes = []
        self._segment = 0

    def _prepare(self, request):
        if self.mode == "evidence_shadow":
            return request
        original = request.system_message
        system = append_content(original, "\n\n" + RULES) if original else SystemMessage(content=RULES)
        if self.mode == "evidence_prompt":
            return request.override(system_message=system)
        raw = [digest(message_value(m)) for m in request.messages]
        # execute()'s existing empty-response recovery starts a fresh graph.
        # Make that a declared boundary, not an apparent prefix failure.
        reset = bool(self._raw and (len(raw) < len(self._raw) or raw[:len(self._raw)] != self._raw))
        if reset:
            self._suffixes = {}
            self._last_summary = None
            self._segment += 1
        old_count = 0 if reset else len(self._raw)
        summary = self.ledger.summary()
        candidate = None
        if not self._raw or reset:
            candidate = next((i for i, m in enumerate(request.messages) if isinstance(m, HumanMessage)), None)
        else:
            # Decorate only after the graph has returned all outstanding tool
            # calls. A request with a partial batch receives no new projection.
            calls = {c["id"] for m in request.messages for c in getattr(m, "tool_calls", [])}
            replies = {m.tool_call_id for m in request.messages if isinstance(m, ToolMessage)}
            if calls <= replies:
                candidate = next((i for i in range(len(raw) - 1, old_count - 1, -1)
                                  if isinstance(request.messages[i], ToolMessage)), None)
        if candidate is not None and summary and summary != self._last_summary:
            self._suffixes[candidate] = MARKER + summary
            self._last_summary = summary
            self.ledger.injections.append({"segment": self._segment, "message_index": candidate,
                                           "tool_call_id": getattr(request.messages[candidate], "tool_call_id", None),
                                           "raw_message_sha256": raw[candidate], "text": MARKER + summary})
        messages = [append_content(m, self._suffixes[i]) if i in self._suffixes else m
                    for i, m in enumerate(request.messages)]
        self._raw = raw
        return request.override(system_message=system, messages=messages)

    def _model_request(self, request):
        try:
            result = self._prepare(request)
        except Exception as exc:
            self._error(exc)
            # Preserve already committed decorations on observer failure. This
            # still passes through exactly one original model request.
            try:
                messages = [append_content(m, self._suffixes[i]) if i in self._suffixes and
                            i < len(self._raw) and digest(message_value(m)) == self._raw[i] else m
                            for i, m in enumerate(request.messages)]
                system = request.system_message
                if self.mode != "evidence_shadow":
                    system = append_content(system, "\n\n" + RULES) if system else SystemMessage(content=RULES)
                result = request.override(system_message=system, messages=messages)
            except Exception as fallback_error:
                self._error(fallback_error)
                result = request
        try:
            hashes = [digest(message_value(m)) for m in ([result.system_message] if result.system_message else []) + result.messages]
            common = 0
            for a, b in zip(hashes, self._previous_hashes):
                if a != b:
                    break
                common += 1
            self.ledger.model_requests.append({
                "request_index": len(self.ledger.model_requests), "segment": self._segment,
                "mode": self.mode, "scope": "pre_provider_langchain_messages_not_wire_payload",
                "message_sha256": hashes, "request_messages_sha256": digest(hashes),
                "previous_message_count": len(self._previous_hashes), "common_prefix_messages": common,
                "previous_prefix_preserved": bool(self._previous_hashes and common == len(self._previous_hashes)),
            })
            self._previous_hashes = hashes
        except Exception as exc:
            self._error(exc)
        return result
